// Writes the <link rel="modulepreload"> list into index.html (Roadmap 2, G1 — fast start).
// Without it the browser finds our ~240 code files one import level at a time (each level waits
// a network round trip — seconds on mobile data). With it, all of them download at once.
// No build step: the files stay as they are; only this list in index.html is generated.
//
//   node tools/make-preload.js            update index.html
//   node tools/make-preload.js --check    exit 1 if the list is out of date (run before a commit)
//
// RUN IT after adding, renaming or deleting a file in src/ (a stale entry = a 404 in the console,
// which the smoke test reports). It follows static imports from src/main.js and from every
// feature in src/features/index.js (those are loaded with import() at boot).

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const HTML = path.join(ROOT, 'index.html');
const START = '<!-- preload:start (generated by tools/make-preload.js) -->';
const END = '<!-- preload:end -->';

const importRe = /(?:^|[;\s])(?:import|export)\s[^'"`]*?from\s*['"]([^'"]+)['"]|(?:^|[;\s])import\s*['"]([^'"]+)['"]/g;
const dynamicRe = /import\(\s*['"]([^'"]+)['"]\s*\)/g;

function deps(file, dynamic) {
  const src = fs.readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  const out = [];
  for (const m of src.matchAll(importRe)) out.push(m[1] || m[2]);
  for (const m of src.matchAll(dynamicRe)) if (dynamic || m[1].startsWith('three/addons/')) out.push(m[1]); // loaders used at boot
  for (const s of out) if (s.startsWith('three/addons/')) addons.add(s.slice('three/addons/'.length));
  return out.filter((s) => s.startsWith('.')).map((s) => path.resolve(path.dirname(file), s));
}
const addons = new Set(); // three.js add-ons (loaders, post effects) — mapped to the import-map URL

const seen = new Set();
function walk(file, dynamic = false) {
  if (seen.has(file) || !fs.existsSync(file)) return;
  seen.add(file);
  for (const d of deps(file, dynamic)) walk(d);
}
walk(path.join(ROOT, 'src/features/index.js'), true); // every feature folder (first: main.js imports it statically too)
walk(path.join(ROOT, 'src/main.js'));

const html = fs.readFileSync(HTML, 'utf8');
const three = (html.match(/"three"\s*:\s*"([^"]+)"/) || [])[1];
const addonBase = (html.match(/"three\/addons\/"\s*:\s*"([^"]+)"/) || [])[1];
const cdn = [three, ...(addonBase ? [...addons].sort().map((a) => addonBase + a) : [])].filter(Boolean);
const lines = [...seen].map((f) => path.relative(ROOT, f).split(path.sep).join('/')).sort();
const block = [START, ...cdn.map((u) => `  <link rel="modulepreload" href="${u}">`), ...lines.map((f) => `  <link rel="modulepreload" href="${f}">`), `  ${END}`].join('\n');

let next;
if (html.includes(START)) next = html.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`), block.trimEnd().replace(/^ {2}/, ''));
else next = html.replace(/(<\/script>\s*\n)(?=[\s\S]*<\/head>)/, `$1  ${block}\n`); // right after the import map

if (process.argv.includes('--check')) {
  if (next !== html) { console.log('index.html preload list is OUT OF DATE — run: node tools/make-preload.js'); process.exit(1); }
  console.log(`preload list ok (${lines.length} files)`);
} else {
  fs.writeFileSync(HTML, next);
  console.log(`index.html: ${lines.length} code files + ${cdn.length} three.js files preloaded`);
}
